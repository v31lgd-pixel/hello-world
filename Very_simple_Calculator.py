num1 = int(input("Enter your number A here: "))
num2 = int(input("Enter your number B here: "))
op = input("Enter what type of operation would you want to do: ") 

if op == "+":
  print(num1 + num2)

if op == "-":
  print(num1 - num2)

if op == "*":
  print(num1 * num2)

if op == "/":
  print(num1 / num2)

if op == "%":
  print(num1 % num2)

if op == "**":
  print(num1 ** num2)

print("end of code")

